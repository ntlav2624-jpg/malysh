import math

def simulate_feedback_loop():
    print("--- [Малыш v3.1] Контур обратной связи: Растяжение ➔ Нагрев ➔ Плазма ---")
    
    alpha_s = 0.3
    sigma = 0.18
    b_field = 567.0  # МэВ^2 (наш ключевой параметр)
    
    # Базовая критическая температура с учетом поля 567
    t_c = 155.0 - (20.0 * math.tanh(b_field / 1000.0)) # ~144.7 МэВ
    
    print(f"Параметр контура (567) | Критическая температура T_c = {t_c:.1f} МэВ\n")
    print(f"{'Радиус r (фм)':<14} | {'Энергия V(r) (ГэВ)':<20} | {'Температура T (МэВ)':<20} | Статус контура")
    print("-" * 75)
    
    r_start = 0.5
    r_end = 6.0
    steps = 25
    step_size = (r_end - r_start) / steps
    
    r = r_start
    plasma_reached = False
    
    while r <= r_end:
        # 1. Рассчитываем потенциал (энергию натяжения)
        coulomb = - (4 * alpha_s) / (3 * r)
        v = coulomb + (sigma * r)
        
        # 2. Контур обратной связи: переводим энергию растяжения в температуру (МэВ)
        # Коэффициент пересчета энергии струны в тепловую энергию среды
        thermal_energy = v * 850.0  # эмпирический коэффициент связи механики и термодинамики
        
        status = "Накопление энергии"
        if thermal_energy >= t_c and not plasma_reached:
            plasma_reached = True
            status = "🔥 САМОРАЗОГРЕВ: ПЛАЗМА!"
        elif thermal_energy >= t_c:
            status = "⚡ Кварк-глюонный суп"
            
        print(f"{r:<14.2f} | {v:<20.3f} | {thermal_energy:<20.1f} | {status}")
        r += step_size
        
    print("-" * 75)
    if plasma_reached:
        print(f"\n[Малыш]: Замкнутый контур сработал успешно!")
        print(f"[Малыш]: Вывод: механическая работа по растяжению струны выделила достаточно тепла, чтобы вакуум расплавился изнутри без внешнего нагрева!")
    else:
        print(f"\n[Малыш]: Энергии растяжения не хватило для выхода на плато плазмы.")

if __name__ == "__main__":
    simulate_feedback_loop()
